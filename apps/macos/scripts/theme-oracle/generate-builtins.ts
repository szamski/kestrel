// Generates apps/macos/T3Kit/Sources/T3Theme/ThemeBuiltIns.swift from packages/shared/src/themePalettes.ts.
//   node apps/macos/scripts/theme-oracle/generate-builtins.ts > apps/macos/T3Kit/Sources/T3Theme/ThemeBuiltIns.swift
import {
  BUILT_IN_THEMES,
  T3_CODE_DARK_THEME_COLORS,
  T3_CODE_LIGHT_THEME_COLORS,
  THEME_COLOR_ROLES,
  type ThemeColors,
} from "../../../../packages/shared/src/themePalettes.ts";

const palette = (colors: ThemeColors, indent: string) =>
  `ThemeColors(ordered: [\n${THEME_COLOR_ROLES.map((role) => `${indent}  "${colors[role]}",`).join("\n")}\n${indent}])`;

const lines: string[] = [
  "// Generated by apps/macos/scripts/theme-oracle/generate-builtins.ts from packages/shared/src/themePalettes.ts. Do not edit.",
  "import Foundation",
  "",
  "extension ThemeDefinition {",
  "  /// The standard T3 Code palette (no theme installed), captured from the web's stock tokens.",
  `  public static let standardLightColors = ${palette(T3_CODE_LIGHT_THEME_COLORS, "  ")}`,
  `  public static let standardDarkColors = ${palette(T3_CODE_DARK_THEME_COLORS, "  ")}`,
  "",
];
const names: string[] = [];
for (const theme of BUILT_IN_THEMES) {
  const name = theme.id.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  names.push(name);
  const variants = Object.entries(theme.variants ?? {})
    .map(([appearance, colors]) => `.${appearance}: ${palette(colors, "    ")}`)
    .join(",\n    ");
  lines.push(
    `  public static let ${name} = ThemeDefinition(`,
    `    id: "${theme.id}", label: "${theme.label}", appearance: .${theme.appearance},`,
    `    colors: ${palette(theme.colors, "    ")},`,
    `    variants: [${variants}],`,
    `    sidebarArtwork: ${theme.sidebarArtwork === true})`,
    "",
  );
}
lines.push(`  public static let builtIns: [ThemeDefinition] = [${names.join(", ")}]`, "}", "");
console.log(lines.join("\n"));
